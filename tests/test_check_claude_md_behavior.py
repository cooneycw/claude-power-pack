# --- Verified generated documentation distribution (issue #861) --------------------
#
# The bundler copies a canonical document into a generated skill so the link a command
# body publishes still resolves in an installed skill. That copy is DISTRIBUTION of
# docs/, not a second policy - but the allowance has to be earned per file, or it is
# just an exemption for anything filed under a generated-looking path.
#
# These tests pin the shape of the allowance from both sides: the intended copies pass,
# and every way of not being an intended copy still fails.

LIFECYCLE_POLICY = (
    "# Knowledge lifecycle\n\n"
    f"{behavior.NORMATIVE_TABLE_MARKER}\n"
    "|---|---|\n"
    "| A rule | a behavioural test |\n"
)
GENERATED_MARKER = "<!-- GENERATED by claude-power-pack - scripts/codex-skill-sync.py; edit x instead -->"


def _distribution_repo(
    root: Path,
    *,
    managed: bool = True,
    canonical: bool = True,
    copy_text: str | None = None,
    with_bundler: bool = True,
) -> Path:
    """A repo with one generated skill carrying a copy of the lifecycle policy."""
    (root / "CLAUDE.md").write_text("Read docs on demand.", encoding="utf-8")
    _write_fixture(root)
    docs = root / "docs"
    docs.mkdir(exist_ok=True)
    (docs / "safety.md").write_text("Never output secrets in responses.", encoding="utf-8")
    if canonical:
        (docs / "agents").mkdir(parents=True, exist_ok=True)
        (docs / "agents" / "knowledge-lifecycle.md").write_text(
            LIFECYCLE_POLICY, encoding="utf-8"
        )

    skill = root / "codex" / "skills" / "flow-auto"
    (skill / "docs" / "agents").mkdir(parents=True, exist_ok=True)
    (skill / "SKILL.md").write_text(
        (GENERATED_MARKER if managed else "# Hand written skill") + "\n\nBody.\n",
        encoding="utf-8",
    )
    (skill / "docs" / "agents" / "knowledge-lifecycle.md").write_text(
        LIFECYCLE_POLICY if copy_text is None else copy_text, encoding="utf-8"
    )

    if with_bundler:
        scripts = root / "scripts"
        scripts.mkdir(exist_ok=True)
        # The REAL bundler, so `is_managed` is the same predicate that writes the files.
        # Its sibling check-md-relative-links.py comes along too (#1494): the
        # bundler's `rewrite_mirror_links` loads it by path relative to wherever
        # the bundler itself was loaded from, so a fixture claiming to carry the
        # real bundler needs this real dependency beside it, not just the one file.
        real_dir = Path(__file__).parents[1] / "scripts"
        for name in ("codex-skill-sync.py", "check-md-relative-links.py"):
            (scripts / name).write_text(
                (real_dir / name).read_text(encoding="utf-8"), encoding="utf-8"
            )
    return skill


def _kinds(root: Path) -> list[str]:
    return [f.kind for f in behavior.check_tree(root)]


def test_a_verified_generated_copy_is_distribution_not_a_second_policy(tmp_path) -> None:
    _distribution_repo(tmp_path)

    assert _kinds(tmp_path) == []


def test_an_altered_generated_copy_is_still_reported(tmp_path) -> None:
    """The whole point of verifying: a copy that drifted is no longer a copy."""
    _distribution_repo(tmp_path, copy_text=LIFECYCLE_POLICY + "\nLocally edited.\n")

    assert "duplicated-lifecycle-policy" in _kinds(tmp_path)


def test_a_copy_in_an_unmanaged_skill_is_still_reported(tmp_path) -> None:
    """A hand-curated skill dir is authored content, whatever it is filed under."""
    _distribution_repo(tmp_path, managed=False)

    assert "duplicated-lifecycle-policy" in _kinds(tmp_path)


def test_a_copy_with_no_canonical_source_is_still_reported(tmp_path) -> None:
    """Provenance case: nothing upstream owns this, so it is not distribution."""
    _distribution_repo(tmp_path, canonical=False)

    assert "duplicated-lifecycle-policy" in _kinds(tmp_path)


def test_the_allowance_fails_closed_without_the_bundler(tmp_path) -> None:
    """Unverifiable is reported, never waved through."""
    _distribution_repo(tmp_path, with_bundler=False)

    assert "duplicated-lifecycle-policy" in _kinds(tmp_path)


def test_policy_pasted_into_a_generated_command_body_is_still_reported(tmp_path) -> None:
    """The allowance covers <skill>/docs/ only - never the command body itself."""
    skill = _distribution_repo(tmp_path)
    (skill / "reference.md").write_text(LIFECYCLE_POLICY, encoding="utf-8")

    findings = [f for f in behavior.check_tree(tmp_path) if "reference.md" in f.detail]

    assert [f.kind for f in findings] == ["duplicated-lifecycle-policy"]


# --- The mirror-provenance note's own exemption (issue #1408) --------------
#
# `PROVENANCE.md` lists every byte-identical bundled path by name, which can
# legitimately include `docs/agents/knowledge-lifecycle.md` for a skill that
# bundles it as verified distribution (above). The note itself must not then
# be read as a NEW non-boundary pointer to that policy, since its entire
# content is generator-assembled filenames, never free prose.


def test_a_managed_skills_provenance_note_naming_the_lifecycle_doc_is_exempt(tmp_path) -> None:
    skill = _distribution_repo(tmp_path)
    (skill / "PROVENANCE.md").write_text(
        "<!-- GENERATED by claude-power-pack - scripts/codex-skill-sync.py; do not edit. -->\n\n"
        "- `docs/agents/knowledge-lifecycle.md`\n",
        encoding="utf-8",
    )

    assert "non-boundary-lifecycle-pointer" not in _kinds(tmp_path)


def test_an_unmanaged_skills_provenance_note_is_still_reported(tmp_path) -> None:
    """The exemption is earned by `is_managed`, not by the filename alone."""
    skill = _distribution_repo(tmp_path, managed=False)
    (skill / "PROVENANCE.md").write_text(
        "<!-- GENERATED by claude-power-pack - scripts/codex-skill-sync.py; do not edit. -->\n\n"
        "- `docs/agents/knowledge-lifecycle.md`\n",
        encoding="utf-8",
    )

    assert "non-boundary-lifecycle-pointer" in _kinds(tmp_path)


def test_the_real_repo_bundled_docs_are_recognised_as_distribution(tmp_path) -> None:
    """Against the actual tree, not a fixture: the shipped copies must pass.

    Paired with the failure cases above, this is what distinguishes a working
    allowance from a check that stopped looking at codex/skills entirely.
    """
    root = Path(__file__).parents[1]
    bundled = sorted((root / "codex" / "skills").glob("*/docs/**/*.md"))
    assert bundled, "no bundled docs found; this pin is stale"
    bundler = behavior._load_bundler(root)
    assert bundler is not None, "the bundler could not be imported"
    is_managed = bundler.is_managed

    unverified = [
        str(path.relative_to(root))
        for path in bundled
        if not behavior.is_verified_generated_doc(path, root, is_managed)
    ]

    assert not unverified, "shipped copies not recognised as distribution: " + ", ".join(unverified)


# --- is_verified_generated_doc widened from byte-identical to link-rewrite-aware
# (#1494 review). A tolerant comparison is exactly how this instrument could
# stop distinguishing a hand-edited mirror from a faithful one, so its own
# discriminating power needs a direct case: a mirror that differs by something
# OTHER than the known rewrite must still fail, even though a mirror that
# differs ONLY by the rewrite must pass.


def _link_rewrite_repo(root: Path, *, with_prose_edit: bool) -> Path:
    """One managed skill bundling a canonical doc whose one link is rewritten.

    `with_prose_edit=False`: the bundled copy is EXACTLY what
    `rewrite_mirror_links` would produce - the positive case.
    `with_prose_edit=True`: the bundled copy also carries one changed prose
    line elsewhere, link untouched - the negative case this test exists for.
    """
    (root / "CLAUDE.md").write_text("Read docs on demand.", encoding="utf-8")
    _write_fixture(root)
    (root / "docs").mkdir(exist_ok=True)
    (root / "docs" / "other.md").write_text("# Other\n\nUpstream-only target.\n", encoding="utf-8")
    source_rel = root / "docs" / "agents"
    source_rel.mkdir(parents=True, exist_ok=True)
    source_text = (
        "# Widened check\n\n"
        "See [other](../other.md) for background.\n\n"
        "A rule a behavioural test can see.\n"
    )
    (source_rel / "widened-check.md").write_text(source_text, encoding="utf-8")

    scripts = root / "scripts"
    scripts.mkdir(exist_ok=True)
    real_dir = Path(__file__).parents[1] / "scripts"
    for name in ("codex-skill-sync.py", "check-md-relative-links.py"):
        (scripts / name).write_text((real_dir / name).read_text(encoding="utf-8"), encoding="utf-8")

    skill = root / "codex" / "skills" / "flow-auto"
    skill_docs = skill / "docs" / "agents"
    skill_docs.mkdir(parents=True, exist_ok=True)
    (skill / "SKILL.md").write_text(GENERATED_MARKER + "\n\nBody.\n", encoding="utf-8")

    bundler = behavior._load_bundler(root)
    assert bundler is not None
    mirrored = {"SKILL.md", "docs/agents/widened-check.md"}
    rewritten = bundler.rewrite_mirror_links(
        source_text, source_rel / "widened-check.md", "docs/agents/widened-check.md", mirrored
    )
    assert "(../other.md)" not in rewritten and "https://github.com" in rewritten, (
        "fixture's link was not rewritten; test proves nothing"
    )
    if with_prose_edit:
        rewritten = rewritten.replace(
            "A rule a behavioural test can see.", "A DIFFERENT rule, never generated this way."
        )
    (skill_docs / "widened-check.md").write_text(rewritten, encoding="utf-8")
    return skill


def test_a_link_only_rewrite_is_still_a_verified_copy(tmp_path: Path) -> None:
    """The positive case: the ONLY difference from source is the known rewrite."""
    skill = _link_rewrite_repo(tmp_path, with_prose_edit=False)
    bundler = behavior._load_bundler(tmp_path)
    assert bundler is not None

    assert behavior.is_verified_generated_doc(
        skill / "docs" / "agents" / "widened-check.md", tmp_path, bundler.is_managed
    )


def test_a_rewrite_plus_an_unrelated_edit_is_not_a_verified_copy(tmp_path: Path) -> None:
    """The negative case this check exists to still catch (#1494 review).

    Paired with the test above: tolerating the rewrite must not also tolerate
    an unrelated hand edit riding along with it.
    """
    skill = _link_rewrite_repo(tmp_path, with_prose_edit=True)
    bundler = behavior._load_bundler(tmp_path)
    assert bundler is not None

    assert not behavior.is_verified_generated_doc(
        skill / "docs" / "agents" / "widened-check.md", tmp_path, bundler.is_managed
    )


def test_the_negative_case_reds_a_deliberately_blind_variant(tmp_path: Path) -> None:
    """Proves the check above is a real discriminator, not a tautology.

    A "verified" predicate that only confirms the path is managed and a
    source exists - never reading either file's content - would pass the
    hand-edited mirror too. The real check must disagree with it.
    """
    skill = _link_rewrite_repo(tmp_path, with_prose_edit=True)
    bundler = behavior._load_bundler(tmp_path)
    assert bundler is not None
    path = skill / "docs" / "agents" / "widened-check.md"

    def blind_is_verified(path: Path, root: Path, is_managed) -> bool:
        source = behavior._canonical_source(path, root)
        skill_dir = root.joinpath(
            *behavior.SKILLS_ROOT, path.relative_to(root.joinpath(*behavior.SKILLS_ROOT)).parts[0]
        )
        return source is not None and source.is_file() and is_managed(skill_dir)

    assert blind_is_verified(path, tmp_path, bundler.is_managed), (
        "the blind variant must agree the fixture LOOKS verifiable, or it isn't "
        "exercising the same inputs as the real check"
    )
    assert not behavior.is_verified_generated_doc(path, tmp_path, bundler.is_managed), (
        "the real check must red where the blind variant cannot - otherwise "
        "widening it to tolerate link rewrites cost its discriminating power"
    )
