"""Codex expected output from the unchanged, pinned generator."""
from __future__ import annotations

import os
import re
import stat
import subprocess
import sys
import tempfile
from pathlib import Path

from .driver import _source_git
from .host import CopyAdapter
from .models import AdapterError, ExpectedBuild, ExpectedMember, ExpectedPackage, build_manifest_sha256


class CodexAdapter(CopyAdapter):
    harness = "codex"
    prefix = (".codex",)

    def legacy_source(self, name, content):
        text = content.decode(errors="replace")
        if text.startswith("---"):
            sections = re.split(r"(?m)^---[ \t]*$", text, maxsplit=2)
            if len(sections) != 3 or sections[0]:
                return False
            text = sections[-1]
        first = next((line for line in text.splitlines() if line.strip()), "")
        return first.startswith("<!-- GENERATED by claude-power-pack - scripts/codex-skill-sync.py;")

    def build(self, revision, policy):
        if self._build is not None and self._build.revision == revision.commit:
            return self._build
        tracked = _source_git(revision, ["ls-tree", "-rz", revision.commit])
        if tracked.returncode:
            raise AdapterError("Codex source inventory unavailable", exit_code=4)
        for row in tracked.stdout.split(b"\0"):
            if not row:
                continue
            head, name = row.split(b"\t", 1)
            fixture = name.startswith(b"controls/") and b"/cases/" in name
            if head.split()[0] == b"120000" and not fixture:
                raise AdapterError("Codex source symlink refused")
        with tempfile.TemporaryDirectory(prefix="cpp-codex-build-") as temporary:
            output = Path(temporary) / "skills"
            result = subprocess.run([sys.executable, str(revision.snapshot_root / "scripts/codex-skill-sync.py"),
                                     "--write", "--output-root", str(output)], capture_output=True, timeout=60,
                                    umask=0o022, env={k: v for k, v in os.environ.items() if not k.startswith("GIT_")})
            if result.returncode:
                raise AdapterError("pinned Codex build failed", exit_code=4)
            packages = []
            for folder in sorted(output.iterdir()):
                if not folder.is_dir():
                    continue
                members = {}
                for path in folder.rglob("*"):
                    if path.is_symlink():
                        raise AdapterError("Codex generated alias refused")
                    if path.is_file():
                        mode = stat.S_IMODE(path.stat().st_mode)
                        members[path.relative_to(folder).as_posix()] = ExpectedMember(path.read_bytes(), mode)
                if "SKILL.md" not in members or not self.legacy_source(folder.name, members["SKILL.md"].content):
                    raise AdapterError("Codex build lacks generated provenance", exit_code=4)
                packages.append(ExpectedPackage(folder.name, "claude-power-pack/codex/" + folder.name, members))
            result_packages = tuple(packages)
            if not result_packages:
                raise AdapterError("Codex expected population is zero", exit_code=4)
            self._build = ExpectedBuild(revision.commit, result_packages,
                                        build_manifest_sha256(revision.commit, result_packages))
        return self._build
